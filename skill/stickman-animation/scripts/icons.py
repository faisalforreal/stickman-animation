def _get_cache_dir() -> str:
    cache_dir = os.path.join(os.path.expanduser("~"), ".gemini", "cache", "stickman_icons")
    os.makedirs(cache_dir, exist_ok=True)
    return cache_dir


def load_icon_svg(name: str) -> str:
    """
    Load SVG string for an icon. Checks offline bundle first,
    then disk cache, and finally fetches from Iconify CDN on-demand.
    """
    clean_name = name.strip().lower().replace("_", "-")
    if clean_name in OFFLINE_ICONS:
        return OFFLINE_ICONS[clean_name]

    # Check disk cache
    cache_dir = _get_cache_dir()
    cache_path = os.path.join(cache_dir, f"{clean_name}.svg")
    if os.path.isfile(cache_path):
        try:
            with open(cache_path, "r", encoding="utf-8") as f:
                return f.read()
        except Exception:
            pass

    # Fetch from CDN on demand (tries Lucide, then Tabler)
    import requests
    prefixes = ["lucide", "tabler", "ph"]
    for pref in prefixes:
        url = f"https://api.iconify.design/{pref}:{clean_name}.svg"
        try:
            resp = requests.get(url, timeout=3)
            if resp.status_code == 200 and resp.text.startswith("<svg"):
                try:
                    with open(cache_path, "w", encoding="utf-8") as f:
                        f.write(resp.text)
                except Exception:
                    pass
                return resp.text
        except Exception:
            continue

    # Fallback placeholder circle with an exclamation point if not found
    return '<svg viewBox="0 0 24 24"><circle cx="12" cy="12" r="10"/><line x1="12" y1="8" x2="12" y2="12"/><circle cx="12" cy="16" r="1"/></svg>'


def get_icon_paths(name: str, box: Tuple[float, float, float, float]) -> List[Path]:
    """Load and normalize icon paths into the target box (center_x, center_y, width, height)."""
    svg_str = load_icon_svg(name)
    return parse_svg(svg_str, target_box=box)
